interface I18nValue {
  locale: Locale;
  t: (key: MessageKey, params?: Record<string, string | number>) => string;
  formatDate: (value: string | Date | null | undefined) => string;
  formatNumber: (value: number | null | undefined, options?: Intl.NumberFormatOptions) => string;
  statusLabel: (value: unknown) => string;
  factLabel: (value: unknown) => string;
  eventLabel: (value: unknown) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function humanize(value: unknown): string {
  return String(value ?? "unknown").replaceAll("_", " ");
}

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  const value = useMemo<I18nValue>(() => {
    const dictionary = dictionaries[locale];
    const t = (key: MessageKey, params: Record<string, string | number> = {}) => {
      let text: string = dictionary[key] || en[key];
      for (const [name, replacement] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(replacement));
      }
      return text;
    };
    const localeName = locale === "vi" ? "vi-VN" : "en-US";
    return {
      locale,
      t,
      formatDate: (input) => {
        if (!input) return t("common.timeUnavailable");
        const date = input instanceof Date ? input : new Date(input);
        if (Number.isNaN(date.getTime())) return t("common.timeUnavailable");
        return new Intl.DateTimeFormat(localeName, { dateStyle: "short", timeStyle: "medium" }).format(date);
      },
      formatNumber: (number, options) => number == null ? "--" : new Intl.NumberFormat(localeName, options).format(number),
      statusLabel: (raw) => {
        const normalized = String(raw ?? "unknown").toLowerCase();
        const key = `status.${normalized}` as MessageKey;
        return key in dictionary ? t(key) : humanize(raw);
      },
      factLabel: (raw) => {
        const normalized = String(raw ?? "Observed");
        const key = `fact.${normalized}` as MessageKey;
        return key in dictionary ? t(key) : humanize(raw);
      },
      eventLabel: (raw) => eventNames[locale][String(raw || "")] || humanize(raw),
    };
  }, [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
